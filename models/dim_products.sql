SELECT
    PRODUCTID,

    CASE
        WHEN COUNT(DISTINCT CATEGORY) = 1
        THEN MAX(CATEGORY)
    END AS CATEGORY,

    CASE
        WHEN COUNT(DISTINCT PRODUCTNAME) = 1
        THEN MAX(PRODUCTNAME)
    END AS PRODUCTNAME,

    CASE
        WHEN COUNT(DISTINCT SUBCATEGORY) = 1
        THEN MAX(SUBCATEGORY)
    END AS SUBCATEGORY,

    COUNT(*) AS SOURCE_ROWS,

    COUNT(DISTINCT PRODUCTNAME) AS NAME_VARIANTS,

    COUNT(DISTINCT PRODUCTNAME) > 1 AS NAME_CONFLICT

FROM {{ ref('stg_products') }}

GROUP BY PRODUCTID
